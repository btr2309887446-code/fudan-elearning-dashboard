import assert from 'node:assert/strict';
import { mkdtempSync, readFileSync, writeFileSync, existsSync, mkdirSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { CredentialStore, publicPreferences, preferencePatch } from '../src/main/credentials.ts';
import { validateIpc, safeExternalUrl } from '../src/main/ipc-security.ts';
import { nextClockDelay } from '../src/core/clock.ts';
const root = mkdtempSync(join(tmpdir(), 'elearning-secret-test-'));
let available = true;
const codec = { available: () => available, encrypt: (v: string) => Buffer.from(v).toString('base64'), decrypt: (v: string) => Buffer.from(v, 'base64').toString('utf8') };
try {
  const path = join(root, 'credentials.json'), legacy = join(root, 'session.json');
  const session = { version: 1, savedAt: '2026-10-27T00:00:00Z', cookies: [], username: 'synthetic' };
  writeFileSync(legacy, JSON.stringify(session)); writeFileSync(`${legacy}.bak`, JSON.stringify(session));
  const store = new CredentialStore(path, codec);
  assert.equal(store.loadSession(legacy)?.file.username, 'synthetic');
  assert.equal(existsSync(legacy), false); assert.equal(existsSync(`${legacy}.bak`), false);
  assert.equal(readFileSync(path, 'utf8').includes('synthetic'), false);
  store.set('llm', 'synthetic-secret');
  const restored = new CredentialStore(path, codec);
  assert.equal(restored.get('llm'), 'synthetic-secret');
  assert.deepEqual(publicPreferences({ theme: 'light', llm: { apiKey: 'secret' }, encryptedPassword: 'secret', summaryCache: {} }), { theme: 'light' });
  assert.deepEqual(preferencePatch({ theme: 'dark', llm: { apiKey: 'injected' } }), { theme: 'dark' });
  assert.throws(() => preferencePatch({ closeToTray: 'yes' }));
  available = false;
  const disk = readFileSync(path, 'utf8');
  assert.equal(restored.set('llm', 'temporary-secret'), false);
  assert.equal(restored.get('llm'), 'temporary-secret'); assert.equal(readFileSync(path,'utf8'),disk);
  restored.clearSession(legacy);
  available = true;
  assert.equal(new CredentialStore(path, codec).loadSession(legacy), null, 'logout survives an unavailable vault');
  const blocked = join(root,'directory'); mkdirSync(blocked);
  const failure = new CredentialStore(join(blocked,'secrets'), codec); failure.set('llm','original');
  // A write error must not acknowledge the new in-memory value.
  const broken = { ...codec, encrypt: () => { throw Error('synthetic failure'); } };
  const failed = new CredentialStore(join(blocked,'secrets'),broken);
  assert.throws(()=>failed.set('llm','replacement')); assert.equal(failed.get('llm'),'original');
  const offlinePath=join(root,'offline.json'); writeFileSync(offlinePath,JSON.stringify(session));
  available=false;
  const offline=new CredentialStore(join(root,'offline-vault'),codec);
  assert.equal(offline.loadSession(offlinePath)?.file.username,'synthetic'); assert.ok(existsSync(offlinePath)); assert.ok(offline.warning);
  available=true;
  assert.equal(new CredentialStore(join(root,'offline-vault'),codec).loadSession(offlinePath)?.file.username,'synthetic'); assert.ok(!existsSync(offlinePath));
  assert.throws(()=>validateIpc('auth:submit',[{username:'a',password:123}]));
  assert.throws(()=>validateIpc('lectures:bind',[1,'course',-1]));
  assert.throws(()=>validateIpc('llm:set',[{apiKey:42}]));
  validateIpc('lectures:list',[1,2,'',0]); validateIpc('data:snapshot',[]);
  assert.equal(safeExternalUrl('file:///C:/secret'),undefined);
  assert.equal(safeExternalUrl('https://user:password@example.com'),undefined);
  assert.equal(nextClockDelay(Date.parse('2026-10-27T23:59:59.000+08:00')),1000);
  console.log('Credential migration, interruption recovery, volatile storage, logout revocation, public configuration, IPC validation and clock boundary checks passed.');
} finally { rmSync(root,{recursive:true,force:true}); }
